/**
 * A deliberately small `.env` parser: `KEY=value`, one per line.
 *
 * No dependency, because this runs before anything is installed in some of the
 * situations it has to work in, and no interpolation, because a value here is a
 * literal credential and expanding `$` inside one would corrupt it.
 */
export function parseEnvText(text) {
  const values = {}
  for (const rawLine of String(text).split(/\r?\n/)) {
    const line = rawLine.trim()
    if (line === "" || line.startsWith("#")) continue

    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line)
    if (!match) continue

    let value = match[2].trim()
    if (
      (value.startsWith('"') && value.endsWith('"') && value.length >= 2) ||
      (value.startsWith("'") && value.endsWith("'") && value.length >= 2)
    ) {
      value = value.slice(1, -1)
    }
    values[match[1]] = value
  }
  return values
}

/** Parse an env file, or `{}` when it does not exist. */
export function readEnvFile(path) {
  if (!existsSync(path)) return {}
  return parseEnvText(readFileSync(path, "utf8"))
}

/** An unset variable and an empty one mean the same thing here: not configured. */
const isSet = (value) => typeof value === "string" && value.trim() !== ""

/**
 * Resolve every managed variable across the three layers, generating whatever
 * is still missing and appending only the new values to `.env.dev.local`.
 *
 * IDEMPOTENT BY CONSTRUCTION. A key that resolves from any layer is left
 * exactly as it is, so a second run generates nothing and a hundredth run
 * generates nothing. Secrets do not rotate on restart, which is what lets
 * `dev:reset` wipe the database while the setup token a developer has in their
 * clipboard stays valid.
 */
export function ensureLocalEnvironment({
  shellEnv = process.env,
  envPath = ENV_PATH,
  localPath = LOCAL_ENV_PATH,
  // Injectable so the test suite can exercise resolution without writing a file
  // into the repository root. Nothing about the DEFAULT path is conditional on
  // being under test — the real callers use the real writer.
  persist = true,
} = {}) {
  const fromEnv = readEnvFile(envPath)
  const fromLocal = readEnvFile(localPath)

  const values = {}
  const sources = {}
  const generated = []

  for (const variable of MANAGED_VARIABLES) {
    const { key } = variable

    // Precedence, highest first. Documented at the top of this file, and the
    // reason a developer's own `.env` is never fought with.
    if (isSet(shellEnv[key])) {
      values[key] = shellEnv[key]
      sources[key] = "shell"
    } else if (isSet(fromEnv[key])) {
      values[key] = fromEnv[key]
      sources[key] = ".env"
    } else if (isSet(fromLocal[key])) {
      values[key] = fromLocal[key]
      sources[key] = LOCAL_ENV_FILENAME
    } else {
      values[key] = variable.deploymentSecret
        ? generateAcceptable(variable.generate)
        : variable.generate()
      sources[key] = "generated"
      generated.push(key)
    }
  }

  if (persist && generated.length > 0) {
    writeLocalEnv(localPath, {
      ...fromLocal,
      ...Object.fromEntries(generated.map((key) => [key, values[key]])),
    })
  }

  return { values, sources, generated }
}

/**
 * Rewrite `.env.dev.local` from scratch, carrying forward anything already in
 * it. Mode 0600 where the platform honours it; Windows ignores the bit and
 * relies on the user's profile ACL, which is the same protection `.env` has.
 */
function writeLocalEnv(path, values) {
  const body =
    `# ${LOCAL_ENV_FILENAME} — generated by scripts/dev/localEnv.mjs.\n` +
    "#\n" +
    "# LOCAL CORE DEVELOPMENT ONLY. Every value here is random, belongs to this\n" +
    "# machine, and is never committed: .gitignore and .dockerignore both name\n" +
    "# this file explicitly. Delete it to have a fresh set generated; that\n" +
    "# invalidates existing sessions and orphans the bundled storage's data,\n" +
    "# so prefer `npm run dev:reset` when you only want a fresh installation.\n" +
    "#\n" +
    "# Values already present in `.env` or the shell are NOT duplicated here —\n" +
    "# this file only ever fills gaps.\n" +
    "\n" +
    Object.entries(values)
      .map(([key, value]) => `${key}=${value}`)
      .join("\n") +
    "\n"

  writeFileSync(path, body, { mode: 0o600 })
}

/**
 * Resolve a variable this module does not manage, through the same layers.
 *
 * For display only — `FLOWCMS_PORT` and `FLOWCMS_ADMIN_PATH` are not secrets
 * and Compose reads them perfectly well on its own. The banner needs them
 * because it prints URLs, and a banner that says `localhost:3000` to somebody
 * who set `FLOWCMS_PORT=8080` in their `.env` is worse than no banner: it sends
 * them to a port nothing is listening on and it looks like the stack is broken.
 */
export function resolveUnmanaged(key, fallback, { shellEnv = process.env } = {}) {
  const layers = [shellEnv[key], readEnvFile(ENV_PATH)[key], readEnvFile(LOCAL_ENV_PATH)[key]]
  return layers.find(isSet) ?? fallback
}

/**
 * Check every managed deployment secret against the policy, whatever layer it
 * came from.
 *
 * Generated values are acceptable by construction, so in practice this judges
 * what a developer put in their own `.env` — and it refuses rather than
 * silently overriding it. Overwriting a value somebody typed on purpose is a
 * worse outcome than stopping to say which rule it broke.
 */
export function validateSecrets({ values, sources }) {
  const problems = []
  for (const variable of MANAGED_VARIABLES) {
    if (!variable.deploymentSecret) continue
    const verdict = classifyLocalSecret(values[variable.key])
    if (verdict.state === "usable") continue
    problems.push({
      key: variable.key,
      source: sources[variable.key],
      // Never the value. See classifyLocalSecret.
      reason: verdict.reason ?? "it is not set",
    })
  }
  return problems
}
